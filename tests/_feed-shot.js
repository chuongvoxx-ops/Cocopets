const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('file://' + path.resolve(__dirname, '../test.html'));
  await page.waitForFunction(() => window.__pp, null, { timeout: 15000 }); await page.waitForTimeout(300);
  await page.evaluate(() => { const P = window.__pp; P.quickStart('Taro'); P.st.unlockAll = true; P.st.pantry = { apple: 3, cookie: 2, melon: 1 }; P.st.dun.best = 30; P.openCard(P.st.uid); });
  await page.waitForTimeout(500);
  const r1 = await page.evaluate(() => { const el = document.querySelector('.feed-panel'); if (el) el.scrollIntoView(); return el ? el.innerText.slice(0, 200) : null; });
  await page.waitForTimeout(200); await page.screenshot({ path: path.resolve(__dirname, '../shots/feed-card.png') });
  const r2 = await page.evaluate(() => { const b = document.querySelector('.feed-panel button'); const before = window.__pp.st.dxp; if (b) b.click(); return { before, after: window.__pp.st.dxp, lv: window.__pp.st.dlv }; });
  await page.waitForTimeout(300);
  await page.evaluate(() => { const P = window.__pp; P.closeSheet(); P.openMap(); P.dun.setMapTab('dungeon', true); P.dun.renderDungeon(); });
  await page.waitForTimeout(500);
  const r3 = await page.evaluate(() => { const el = document.querySelector('.feed-panel'); if (el) el.scrollIntoView({ block: 'center' }); return !!el; });
  await page.waitForTimeout(200); await page.screenshot({ path: path.resolve(__dirname, '../shots/feed-tower.png') });
  console.log(JSON.stringify({ r1, r2, r3 })); console.log('errors', errors.length, errors.slice(0, 3));
  await browser.close();
})();
