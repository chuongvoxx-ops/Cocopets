const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const path = require('path');
(async () => {
  const floor = +(process.argv[2] || 110);
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true });
  await page.goto('file://' + path.resolve(__dirname, '../test.html'));
  await page.waitForFunction(() => window.__pp, null, { timeout: 15000 }); await page.waitForTimeout(300);
  await page.evaluate(() => { const P = window.__pp; P.quickStart('Bot'); P.st.unlockAll = true; P.st.dun.god = true; P.st.energy = 100; P.st.dun.best = 199; P.openMap(); P.dun.setMapTab('dungeon', true); });
  await page.evaluate(n => window.__pp.dun.startDungeon(n, 7), floor);
  await page.waitForFunction(() => window.__pp.arc.state === 'ready', null, { timeout: 15000 });
  await page.evaluate(() => window.__pp.beginPlay()); await page.waitForTimeout(+(process.env.WAIT || 6000));
  const r = await page.evaluate(() => {
    const P = window.__pp, A = P.arc, G = A.game, D = G._dbg, FD = D.FD, c = document.querySelector('canvas').getContext('2d'), K = P.DunFiend.KIT, g = D.g;
    const fl = () => c.getImageData(0, 0, 1, 1);
    const time = (f, n) => { f(); fl(); const t0 = performance.now(); for (let i = 0; i < n; i++) { f(); fl(); } return +((performance.now() - t0) / n).toFixed(2); };
    const out = { act: g.boss && g.boss.act, q: K.Q.q, nprops: FD.S.props.length, nparts: D.parts.length, nobjs: (FD.S.objs || []).length, dpr: A.dpr };
    const W = A.W || G.W || 390, H = A.H || 844;
    out.empty = time(() => {}, 5);
    out.full = time(() => G.draw(c), 5);
    out.arena = time(() => FD.drawArena(c, W, H, D.g.cam || { x: D.me.x, y: D.me.y }, 40 * g.zoom, g.t), 5);
    out.ground = time(() => FD.drawGround(c), 5);
    out.props = time(() => FD.S.props.forEach(p => FD.drawProp(c, p)), 5);
    out.fx = time(() => FD.drawFx(c), 5);
    ['overlay', 'fog', 'light', 'backdrop'].forEach(k => { D.SKIP[k] = true; out['full_no_' + k] = time(() => G.draw(c), 5); D.SKIP[k] = false; });
    const ps = D.parts.splice(0); out.full_noparts = time(() => G.draw(c), 5); D.parts.push(...ps);
    return out;
  });
  console.log(JSON.stringify(r));
  await browser.close();
})();
